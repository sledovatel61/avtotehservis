/**
 * Посадка фото-пластины машины в кадре 3D-фона (круг 35, задание №62).
 *
 * Одна арифметика на троих: шейдер (`shader.ts`), его CPU-порт (`tools/bg3d/ref.mjs`)
 * и замеры (`scripts/bg3d-car-measure.mjs`, `scripts/bg3d-side-ruler.mjs`) обязаны
 * ставить квад одинаково. Иначе кадр в отчёте и кадр на GPU разъедутся — ровно та
 * ошибка, из-за которой три замера круга 33 дали три разных числа.
 *
 * Здесь только геометрия кадра: где центр, какой масштаб, какой подъём. Ни одного
 * пикселя кузова код не рисует: контур целиком лежит в пластине.
 *
 * Единицы — те же, что у сцены (p в шейдере: x уже умножен на aspect, y — от −1 до 1).
 */

/**
 * Полудлина машины в единицах p (в p.x уже умножен aspect).
 *
 * Число не «на глаз»: процедурный силуэт круга 33 занимал в q-пространстве
 * 1,789 ед. сцены по длине (4,905 м × 0,364742), то есть 0,894 полуширины.
 * Пластина встаёт ровно на это место — кадры 1440×900 и 390×844 при этом
 * совпадают с прежними по композиции (машина справа под текстом / по центру),
 * и их видно в отчёте r35-bg-car.
 */
export const PLATE_HALF_LEN = 0.894;

/** Пропорции пластины: ширина/высота файла. Значение подставляет сборка из plate.json. */
export const PLATE_ASPECT = 2.768638;

/**
 * Где стоит машина. Все коэффициенты — из шейдера круга 33 (посадка по aspect),
 * они проверены кадрами 1440×900 и 390×844 и менять их незачем: пластина встаёт
 * ровно туда, где стоял процедурный силуэт.
 *
 *   wide — 1 на широком кадре (aspect ≥ 1,40) и 0 на узком (≤ 0,46);
 *   kx   — тянет к центру по X на узком кадре (0,35)
 *   ky   — прижимает к центру по Y (0,55)
 *   lift — подъём на узком кадре (0,28)
 *   scA  — общий масштаб сцены: на телефоне уменьшается до 0,62 от широкого кадра
 */
export function platePlacement(aspect: number, pointer: [number, number], scroll: number, hy: number): {
  cx: number; cy: number; sc: number; wide: number;
} {
  const ss = (e0: number, e1: number, x: number) => {
    const t = Math.min(1, Math.max(0, (x - e0) / (e1 - e0)));
    return t * t * (3 - 2 * t);
  };
  const depth = 0.58;
  const wide = ss(0.46, 1.40, aspect);
  const kx = 0.35 + (1.0 - 0.35) * wide;
  const ky = 0.55 + (1.0 - 0.55) * wide;
  const scA = (0.80 + (0.46 - 0.80) * depth) * (0.62 + (1.0 - 0.62) * ss(0.40, 0.86, aspect));
  const lift = (1.0 - wide) * 0.28;
  const cx = (0.24 + pointer[0] * 0.10 * (1.0 - depth)) * kx;
  const cy = hy - 0.155 - scroll * 0.05 + pointer[1] * 0.035 - (1.0 - ky) * 0.30 + lift;
  return { cx, cy, sc: scA, wide };
}

/**
 * Линия земли в пластине — доля ВЫСОТЫ ФАЙЛА от верха до линии, на которой стоят шины.
 *
 * Не «низ квада»: при сборке под землёй оставлено поле (padding 8 px), иначе кромка
 * шины упиралась бы в край файла и при фильтрации срезалась. Если посадить тень и
 * отражение на низ квада, они уезжают на эти 8 px вниз — под шинами появляется
 * светлая щель, и тень читается отдельным пятном на полу.
 *
 * Значение подставляет сборка (`tools/bg3d/make-car-plate.mjs`) из `plate.json`,
 * поле `frac.ground`. Руками не править: оно обязано совпадать с файлом.
 */
export const PLATE_GROUND_FRAC = 0.980969;

/**
 * Зазор между низом шин и началом отражения в мокром асфальте, в единицах p.
 *
 * На мокром асфальте отражение не примыкает к шине вплотную: между ними лежит
 * контактная тень. Без зазора отражение прирастает к силуэту, и любой замер по
 * разнице кадров читает его как часть машины (в круге 33 это дало h/L 0,377
 * вместо 0,335 — ровно та ошибка, из-за которой замеры не сходились).
 */
export const PLATE_REFLECTION_GAP = 0.022;

/**
 * Полуразмеры квада пластины в координатах p.
 *
 * Длина кузова в этих координатах задана PLATE_LEN·sc — так пластина занимает ту же
 * долю кадра, что занимал силуэт (проверено кадрами: 1440×900 — 44 %W, 390×844 — 74 %W).
 * Высота считается из пропорций самой пластины и компенсирует aspect: p.x уже умножен
 * на aspect, поэтому по X полуразмер делится на aspect, иначе на телефоне машина
 * растягивается по ширине.
 */
export function plateHalfSize(sc: number): { hx: number; hy: number } {
  const hx = PLATE_HALF_LEN * sc;
  /* Пропорции файла: на экране A = hx/hy (aspect сокращается, потому что p.x уже
     умножен на него). Поэтому hy = hx/A — и кромка не рвётся ни на каком кадре. */
  return { hx, hy: hx / PLATE_ASPECT };
}
