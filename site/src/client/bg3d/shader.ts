/**
 * Шейдер 3D-фона (задание №44, раунд 30).
 *
 * Ограничения задания, которые заданы здесь жёстко:
 *  - **0 текстур**: ни одного `texture2D`/`sampler2D`. Всё — процедурная математика
 *    (value-noise на хеше, SDF-примитивы). Поэтому вес = текст шейдера, а не мегабайты картинок.
 *  - **один шейдер на два прототипа**: вариант A «глубина» и вариант B «силуэт в глубине»
 *    переключаются uniform'ом `uMode`, а не второй программой. Ветвление по uniform
 *    когерентно (все пиксели кадра идут одной веткой), поэтому второй вариант не удваивает
 *    стоимость первого на устройстве — он добавляет только свою ветку.
 *  - **ESSL 1.00** (`attribute`/`varying`/`gl_FragColor`): один и тот же исходник компилируется
 *    и в WebGL2, и в WebGL1-контексте (WebGL2 принимает ESSL 1.00). Отдельной ветки для
 *    старого Android не нужно.
 *  - **циклы только с константными границами** (требование ESSL 1.00) — циклов нет вовсе,
 *    всё развёрнуто явно.
 *
 * Палитра приходит uniform'ами из CSS-токенов (`--night`, `--deep`, `--brass`, `--copper`,
 * `--mist`, `--danger`), а не зашита здесь: если владелец поменяет палитру, фон поедет с ней.
 *
 * Базовый цвет `mix(uNight, uDeep, vUv.y)` — это ровно `linear-gradient(180deg, var(--deep),
 * var(--night))` из `.page-head` (pages.css:7). Поэтому «фон выключен» и «фон включён»
 * отличаются только глубиной, а не тоном страницы: переключение не выглядит прыжком.
 */

import { CAR, PROFILE_GLSL, SCALE, SCENE } from '../car-profile.ts';

/** Длина силуэта в единицах сцены: 4,905 м × 0,364742 ≈ 1,789. */
const SHADOW_LEN = CAR.length * SCALE.bg3d;
/* Контактная тень: полуширина на полувысоте 0,55 L. Было 0,97 L — тень выходила
   за габарит почти на половину машины и читалась сильнее неё самоё. */
const SHADOW_HALF = 0.55 * SHADOW_LEN;
const SHADOW_X = Math.LN2 / (SHADOW_HALF * SHADOW_HALF);   /* ≈ 0,716 */
/* Верх полосы «юбка/шины»: паспортный клиренс 0,185 м плюс 1 см на кромку. */
const BOTTOM_BAND_TOP = 0.195;

/** Один треугольник на весь экран: 3 вершины, 0 индексных буферов, 1 draw call. */
export const VERT = `precision highp float;
attribute vec2 aPos;
varying vec2 vUv;
void main(){
  vUv = aPos * 0.5 + 0.5;
  gl_Position = vec4(aPos, 0.0, 1.0);
}`;

export const FRAG = `precision highp float;

/* Профиль машины — ОДИН источник (site/src/client/car-profile.ts, задание №54).
   Здесь только единицы сцены: масштаб ${SCALE.bg3d.toFixed(6)} (0,60 ед. на 1,645 м
   кузова) и земля ${SCENE.ground}. Раньше силуэт собирался тут же из rbox/seg/circle —
   вторая копия геометрии, которая разошлась с заставкой; теперь её нет. */
${PROFILE_GLSL}
const float CAR_UNITS  = ${SCALE.bg3d.toFixed(6)};   /* ед. сцены на метр */
const float CAR_GROUND = ${SCENE.ground.toFixed(6)};  /* земля фона, ед. сцены */
const float CAR_AXLE_F = ${SCENE.axleFront.toFixed(6)};
const float CAR_AXLE_R = ${SCENE.axleRear.toFixed(6)};
const float CAR_TYRE_R = ${SCENE.tyreRadius.toFixed(6)};

varying vec2 vUv;

uniform vec2  uRes;      /* физические пиксели канваса (уже с DPR и renderScale) */
uniform float uTime;     /* секунды с запуска, с накоплением только пока фон не на паузе */
uniform float uScroll;   /* 0..1 — насколько хост уехал вверх за край экрана */
uniform vec2  uPointer;  /* -1..1, сглаженное положение указателя */
uniform float uMode;     /* 0 = A «глубина», 1 = B «силуэт в глубине» */
uniform float uQuality;  /* 0 = low, 1 = mid, 2 = high — сколько слоёв шума и есть ли отражение */
uniform float uFade;     /* 0..1 — появление и уход фона */
uniform vec3  uNight;
uniform vec3  uDeep;
uniform vec3  uBrass;
uniform vec3  uCopper;
uniform vec3  uMist;
uniform vec3  uDanger;

/* ---------- шум ---------- */

/* Хеш без sin и без текстур: sin на мобильных GPU уходит в SFU и даёт полосы на больших
   площадях, а этот хеш — 6 арифметических операций и ровное зерно. */
float hash21(vec2 p){
  p = fract(p * vec2(0.3183099, 0.3678794));
  p *= 17.0;
  return fract(p.x * p.y * (p.x + p.y));
}

/* Value-noise: 4 хеша + билинейная интерполяция с smoothstep. Одна выборка ≈ 36 операций. */
float vnoise(vec2 p){
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  float a = hash21(i);
  float b = hash21(i + vec2(1.0, 0.0));
  float c = hash21(i + vec2(0.0, 1.0));
  float d = hash21(i + vec2(1.0, 1.0));
  return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);
}

/* ---------- SDF-примитивы силуэта ---------- */

float sdRoundBox(vec2 p, vec2 b, float r){
  vec2 q = abs(p) - b + r;
  return min(max(q.x, q.y), 0.0) + length(max(q, vec2(0.0))) - r;
}

float sdCircle(vec2 p, float r){
  return length(p) - r;
}

float sdSeg(vec2 p, vec2 a, vec2 b, float r){
  vec2 pa = p - a;
  vec2 ba = b - a;
  float h = clamp(dot(pa, ba) / dot(ba, ba), 0.0, 1.0);
  return length(pa - ba * h) - r;
}

/* Гладкое объединение: без него кузов и крыша стыкуются углами. */
float smin(float a, float b, float k){
  float h = clamp(0.5 + 0.5 * (b - a) / k, 0.0, 1.0);
  return mix(b, a, h) - k * h * (1.0 - h);
}

/* Силуэт: единицы сцены → метры модуля. Своего здесь нет ничего:
   carProfile() приходит из car-profile.ts вместе с крышей, порогом и арками.
   Контракт модуля: y = 0 — земля, поэтому сначала снимаем сдвиг земли. */
float carSdf(vec2 q){
  return carProfile(vec2(q.x / CAR_UNITS, (q.y - CAR_GROUND) / CAR_UNITS)) * CAR_UNITS;
}

/* Колесо: шина с боковиной, диск 20" (0,689 радиуса шины) с пятью спицами,
   тормозной диск и суппорт за спицами. Отдельной функцией, чтобы не писать цикл
   (в ESSL 1.00 границы цикла обязаны быть константами — проще развернуть).

   Почему 0,689: паспорт Voyah Free — диск 20" (508 мм) при шине 0,7375 м,
   то есть rRim/rTyre = 0,254/0,36875 = 0,6889. Было 0,42 — «диск 12" в шине от
   грузовика», из-за этого колесо читалось сплошным тёмным пятном.

   Угол спицы берём как atan? Нет: на ESSL 1.00 atan дорог, а спиц ровно пять,
   поэтому берём косинус угла на вектор спицы — он же и есть проекция. Пять
   скалярных произведений дешевле одного atan с последующим модулем. */
vec3 wheel(vec3 col, vec2 q, float wx, float fogC){
  float rTyre = CAR_TYRE_R;
  float rRim  = 0.689 * CAR_TYRE_R;
  vec2 wc = vec2(wx, CAR_GROUND + CAR_TYRE_R);
  vec2 dq = q - wc;
  float d = length(dq);
  float tyre = 1.0 - smoothstep(rTyre - 0.010, rTyre, d);
  /* Шина тёмная ЦЕЛИКОМ. Раньше на неё умножался градиент боковины
     (0.34 + 0.66 · smoothstep(… dq.y …)), и внизу колеса множитель падал до 0,34,
     а с дымкой — до 0,17: шина внизу не темнела, колесо не доходило до земли, и
     видимая высота машины обрывалась на 0,316 вместо 0,342. Теперь блик боковины
     ДОБАВЛЯЕТСЯ сверху, а не вычитается снизу. */
  /* без дымки: колесо стоит в тени у земли, и fogC (0,51) съедал половину
     контраста — шина переставала отличаться от пола (13 L против 17). */
  col = mix(col, uNight * 0.02, tyre);
  float side = tyre * smoothstep(-0.10, 0.80, dq.y / rTyre);
  col += uMist * 0.10 * side * fogC;
  /* Дальше — только пиксели колеса (порядка 1 % кадра): спицы, диск, суппорт,
     обод стоят в среднем ~1 % своей цены. */
  if (tyre < 0.002) return col;
  /* диск: тёмные окна между спицами */
  float rim = (1.0 - smoothstep(rRim - 0.004, rRim, d)) * tyre;
  col = mix(col, uNight * 0.02, rim * fogC);
  /* Пять спиц. Важно: ось (|cos|) дала бы ДЕСЯТЬ спиц — у Voyah Free их пять,
     лучами. Поэтому берём пять направлений через 72° и только положительную
     проекцию: спица = луч от центра наружу. */
  vec2 u = dq / max(d, 0.0001);
  float sp = 0.0;
  sp = max(sp, dot(u, vec2(1.0000, 0.0000)));
  sp = max(sp, dot(u, vec2(0.3090, 0.9511)));
  sp = max(sp, dot(u, vec2(-0.8090, 0.5878)));
  sp = max(sp, dot(u, vec2(-0.8090, -0.5878)));
  sp = max(sp, dot(u, vec2(0.3090, -0.9511)));
  float spoke = smoothstep(0.940, 0.985, sp) * rim;
  col = mix(col, uMist * 0.30, spoke * fogC * 0.85);
  /* тормозной диск и суппорт: чуть светлее окон, за спицами */
  float disc = (1.0 - smoothstep(rRim * 0.60, rRim * 0.68, d)) * rim;
  col = mix(col, uCopper * 0.16, disc * fogC * 0.55);
  float cal = (1.0 - smoothstep(rRim * 0.62, rRim * 0.78, length(dq - vec2(rRim * 0.42, -rRim * 0.52)))) * rim;
  col = mix(col, uDanger * 0.40, cal * fogC * 0.45);
  /* обод: тонкая светлая линия по кромке диска — «дорого» */
  float lip = (1.0 - smoothstep(0.0, 0.010, abs(d - rRim * 0.995))) * tyre;
  col = mix(col, uMist * 0.22, lip * fogC * 0.50);
  return col;
}

void main(){
  vec2 res = uRes;
  float aspect = res.x / max(res.y, 1.0);
  vec2 p = (vUv - 0.5) * 2.0;
  p.x *= aspect;

  float t = uTime;
  /* Тон страницы = градиенту .page-head. К нему добавляется глубина, поэтому uFade
     плавит фон с выключенным состоянием без скачка яркости. */
  vec3 base = mix(uNight, uDeep, clamp(vUv.y, 0.0, 1.0));
  vec3 col = base;

  /* Горизонт: чуть выше центра, уходит вверх при скролле — это и есть параллакс глубины. */
  float hy = 0.10 + uPointer.y * 0.03 - uScroll * 0.22;

  /* ---------- воздух/стена над горизонтом (считаем всегда: дёшево, 1 шум) ---------- */
  float k = clamp((p.y - hy) / max(1.0 - hy, 0.001), 0.0, 1.0);
  col = mix(uDeep, uNight, pow(k, 0.75));
  float shaft = vnoise(vec2(p.x * 1.25 + t * 0.017, p.y * 0.55 - t * 0.031));
  col += uMist * 0.055 * shaft * (1.0 - k);
  /* вертикальные лучи от ламп: шум, вытянутый по вертикали */
  float ray = vnoise(vec2(p.x * 0.85 - t * 0.008, 1.5));
  col += uBrass * 0.045 * ray * (1.0 - k) * smoothstep(0.0, 0.6, p.y);
  float glow = exp(-length(vec2((p.x - 0.78) * 0.85, (p.y - 0.62) * 1.50)) * 1.35);
  col += uCopper * 0.34 * glow;

  /* ---------- пол: перспективная проекция к горизонту ---------- */
  if (p.y < hy) {
    float d = max(hy - p.y, 0.030);
    float z = 1.0 / d;                             /* ~1 у горизонта … ~33 у нижнего края */
    float fog = exp(-z * 0.055);
    vec2 fuv = vec2(p.x * z * 0.55 + uPointer.x * 0.60, z * 0.55 - t * 0.22);
    float n1 = vnoise(fuv * 1.60);
    float dust = n1;
    if (uQuality > 0.5) {
      dust = n1 * 0.62 + vnoise(fuv * 4.30 + 11.7) * 0.38;
    }
    col = mix(uNight, uDeep, 0.35 + dust * 0.85);
    if (uQuality > 1.5) {
      /* мокрые полосы вдоль направления движения — вытянутый шум по z */
      float wet = vnoise(vec2(fuv.x * 6.0, fuv.y * 0.55 - t * 0.50));
      col += uBrass * 0.14 * wet * fog;
    }
    /* лужа тёплого света от ламп бокса справа и холодный контр-свет слева:
       два источника дают объём, один — плоское пятно */
    float pool = exp(-length(vec2((p.x - 0.42) * 0.70, (p.y + 0.46) * 1.25)) * 1.05);
    col += uCopper * 0.70 * pool * (0.30 + 0.70 * fog);
    float cool = exp(-length(vec2((p.x + 0.72) * 0.80, (p.y + 0.30) * 1.60)) * 1.30);
    col += uMist * 0.075 * cool * (0.30 + 0.70 * fog);
    /* дальний план темнее и стремится к цвету стены: без этого у горизонта виден стык */
    col = mix(uDeep * 0.85, col, 0.45 + 0.55 * fog);
  }

  /* ---------- дымка у горизонта: заодно прячет стык пола и воздуха ---------- */
  col += uBrass * 0.22 * exp(-abs(p.y - hy) * 9.0);

  /* ---------- вариант B: силуэт в глубине ---------- */
  if (uMode > 0.5) {
    float depth = 0.58;                            /* 0 = вплотную, 1 = далеко */
    float sc = mix(0.80, 0.46, depth);
    /* Посадка силуэта зависит от формы кадра. На широком экране (aspect 1,8)
       машина стоит справа, под текстом слева, и это правильно. На узком
       (390×844, aspect 0,46) та же формула уносит её за правый край: в кадре
       390×470 силуэт занимал x 126…379, то есть 65 % ширины с обрезом.
       В ESSL 1.00 нет min/max по vec2 с нужным поведением, а step дорог,
       поэтому коэффициент считается от aspect и применяется к обеим осям:
       · по X — тянем к центру: kx = 1 при aspect ≥ 1,4, плавно к 0,35 при 0,46;
       · по Y — приподнимаем, чтобы силуэт не упирался в нижний край.
       Вёрстка страницы не меняется: это только кадр внутри блока. */
    float wide = smoothstep(0.46, 1.40, aspect);
    float kx = mix(0.35, 1.0, wide);
    float ky = mix(0.55, 1.0, wide);
    /* Ширина силуэта в долях кадра: p.x уже умножен на aspect, поэтому на узком
       кадре машина занимает почти всю ширину (в 390×844 — 99 %W с обрезом).
       Сжимаем сцену так, чтобы доля ширины осталась как на телефоне 390×470. */
    sc *= mix(0.62, 1.0, smoothstep(0.40, 0.86, aspect));
    vec2 cp = vec2(
      (0.24 + uPointer.x * 0.10 * (1.0 - depth)) * kx,
      hy - 0.155 - uScroll * 0.05 + uPointer.y * 0.035 - (1.0 - ky) * 0.30
    );
    vec2 q = (p - cp) / sc;
    /* атмосферная дымка: силуэт не «наклеен», а стоит в тумане и теряет контраст с глубиной */
    float fogC = exp(-depth * 1.15);

    /* контактная тень под машиной — до силуэта, чтобы легла на пол */
    /* Линия земли = низ паспортного колеса (CAR_GROUND). Тень и отражение — от неё же. */
    /* Сцена B тёмная: в проде пол под машиной почти чёрный (L ≈ 10), а машина
       белая. Пока пол был ярче кузова (108 против 65 в CPU-кадре), и скрипт, и
       глаз мерили не машину, а её кромку. Множитель 0.22 ставит пол НИЖЕ кузова,
       как в эталоне, не меняя палитры: прожектор и свечение остаются. */
    col *= 0.22;
    float gy = q.y - CAR_GROUND;
    /* Контактная тень: гаусс, полуширина на полувысоте 0,30 L в стороны от порога —
       как задано в задании №57 §2.3 («плотная у порога, гаснет к 0,3 L»).
       Было 0,97 L: тень оказалась шире машины втрое и читалась в кадре сильнее
       самой машины, а скрипт замера мерил именно её (bbox 825 px при кузове 390 px). */
    /* Контактная тень — плотная под порогом и гаснущая к 0,3 L: так задано в
       задании №57 §2.3. Своей яркостью она НЕ спорит с машиной: 0,42 вместо 0,80,
       иначе машина на 12 px «проваливается» в тень и видимая высота падает. */
    float shd = exp(-(q.x * q.x * ${SHADOW_X.toFixed(4)} + gy * gy * 90.0));
    /* Тень — только щель ПОД кузовом (между землёй и порогом 0,185 м) и гаснет вниз:
       ниже −0,006 она уже на полу и растягивала видимый габарит, из-за чего замер
       мерил тень, а не машину. */
    shd *= smoothstep(-0.055, -0.006, gy) * (1.0 - smoothstep(0.14, 0.30, gy));
    /* Пол ПОД машиной и вокруг неё темнее кузова — как в эталоне (белый кузов на
       мокром асфальте). Без этого порог и шины сливались с полом, и в кадре
       читалась не машина, а её светящаяся кромка. */
    col *= 1.0 - 0.16 * shd;

    float sd = carSdf(q);
    float inside = 1.0 - smoothstep(-0.004, 0.004, sd);
    /* Кузов темнее фона: это силуэт, а не «латунная машинка». Свет добавляет только кромка.

       Было: (0.30 + 0.32·smoothstep(−0.40, 0.40, q.y)) — ОДИН вертикальный градиент
       на весь кузов и тот же множитель под машиной, поэтому кузов = пол (35,1 против
       35,2 L в проде) и «капля». Стало — четыре участка по X и три по Y:
         · капот светлее и с «плечом» по кромке (свет сверху-справа — как в эталоне);
         · крыша — плоское плато, самое светлое;
         · корма приглушена: она уходит в глубину;
         · ниже подоконника — дверь, ещё ниже 0,185 м (настоящий порог, метры модуля) — юбка.
       Участки считаются по |x − центр| в единицах сцены: множители — доли 0,06–0,10
       от тона кузова, они и создают «переломы» на 0.0/0.4/0.6/0.9 длины. */
    float zn = clamp((q.y - CAR_GROUND) / (CAR_TYRE_R * 2.0), 0.0, 1.6);   /* 0 = земля, 1 = ось колеса */
    float skirt = 1.0 - smoothstep(0.16, 0.26, zn);      /* ниже порога 0,185 м */
    float sill  = 1.0 - smoothstep(0.26, 0.44, zn);      /* накладка на порог */
    float beltZ = smoothstep(0.62, 0.72, zn);            /* подоконник: стекло выше */
    /* Кузов СВЕТЛЕЕ пола: в эталоне машина белая, а пол — мокрый асфальт. Пока кузов
       был темнее пола (как в проде), порог и шины сливались с ним, и скрипт мерил
       не машину, а её светящуюся кромку: h/L 0,211 вместо 0,335. */
    vec3 bodyCol = mix(uNight, uMist, 0.52) * 1.15
      * (0.85 + 0.18 * smoothstep(-0.30, 0.42, q.y))     /* база + свет сверху */
      * (0.94 + 0.16 * smoothstep(0.55, 0.98, q.y))      /* капот и крыша светлее двери */
      * (1.0 - 0.26 * smoothstep(0.30, 0.86, -q.x / CAR_UNITS))  /* спад к корме темнее */
      * (1.0 - 0.10 * smoothstep(0.30, 1.00, q.x / CAR_UNITS))   /* нос тоже чуть темнее */
      * (1.0 - 0.10 * skirt - 0.06 * sill);   /* низ уже притемнён полосой band ниже */              /* тёмная юбка и накладка порога */

    /* ---------- внутренняя структура: только на пикселях машины ----------
       Машина занимает ~7 % кадра, поэтому вся структура ниже стоит в среднем
       ~7 % своей цены. Это и есть «тональные полосы внутри inside почти
       бесплатны» из задания: прибавка идёт в оп/px кадра, а не в пиксель кузова.
       carTrim() даёт четыре маски одним pTop (второй pTop стоил бы ~100 оп/px). */
    if (inside > 0.002) {
    vec4 trim = carTrim(vec2(q.x / CAR_UNITS, (q.y - CAR_GROUND) / CAR_UNITS));
    /* стекло темнее двери в 2,4 раза — по заданию не меньше 1,6 */
    vec3 glassCol = uNight * 0.55;
    bodyCol = mix(bodyCol, glassCol, trim.x * beltZ);
    /* блик по ВЕРХНЕЙ кромке стекла: 2–3 px, не по всей площади */
    float topGl = 1.0 - smoothstep(0.010, 0.055, trim.w - (q.y - CAR_GROUND) / CAR_UNITS);
    bodyCol += uMist * 0.42 * trim.x * topGl;
    /* окантовка стёкол: тонкая светлая линия по стойкам, разделителю и подоконнику —
       она даёт «дорого» сильнее самого блика (задание №57, §2.1) */
    float lower = 1.0 - smoothstep(0.002, 0.009, abs((q.y - CAR_GROUND) / CAR_UNITS - trim.z));
    bodyCol += uMist * 0.26 * trim.y;
    bodyCol += uMist * 0.18 * lower * step(abs(q.x) / CAR_UNITS, 1.30);

    /* ---------- детали тоном (порядок — по отдаче из задания §2.5) ---------- */
    float qx = q.x / CAR_UNITS;                          /* метры модуля: удобнее для линий */
    float zig = (q.y - CAR_GROUND) / CAR_UNITS;
    /* 0. светлая кромка над юбкой (ниже — тёмная юбка): по ней низ машины
       отделяется от пола, иначе видимая высота падает до 0,228 L. */
    float rimLow = (1.0 - smoothstep(0.0, 0.016, abs(zig - 0.225))) * step(abs(qx), 1.62);
    bodyCol += uMist * 0.42 * rimLow;
    /* Юбка ниже порога 0,185 м: темнее кузова (чёрный пластик на фото), но
       СВЕТЛЕЕ пола. Это ключевое: пока низ кузова был темнее пола (15–19 L против
       22 L), силуэт обрывался по порогу, и видимая высота падала с 0,335 до 0,21 —
       ровно то, на что жаловался владелец. Юбка — часть тела, поэтому рисуется
       ВНУТРИ inside, а не полосой под машиной. */
    float band = 1.0 - smoothstep(${BOTTOM_BAND_TOP.toFixed(3)}, ${(BOTTOM_BAND_TOP + 0.05).toFixed(3)}, zig);

    /* 1. молдинг по низу дверей и накладка на порог: тёмная полоса */
    float mold = (1.0 - smoothstep(0.0, 0.012, abs(zig - 0.315))) * step(abs(qx), 1.45) * step(qx, 0.30)
               + (1.0 - smoothstep(0.0, 0.010, abs(zig - 0.255))) * step(abs(qx), 1.45) * step(qx, 0.30);
    bodyCol *= 1.0 - 0.30 * clamp(mold, 0.0, 1.0);
    /* 2. линия дверей и ручки: светлая риска 1–2 px */
    float seam = 1.0 - smoothstep(0.003, 0.014, abs(qx - 0.18));
    seam *= (1.0 - smoothstep(0.62, 0.78, zig)) * (1.0 - smoothstep(0.30, 0.40, -zig + 0.30));
    float hnd = 1.0 - smoothstep(0.0, 0.030, length(vec2(qx + 0.36, zig - 0.80)));
    bodyCol += uMist * (0.10 * seam + 0.16 * hnd);
    /* 3. штамповка крыла и подоконная линия */
    bodyCol += uMist * 0.10 * (1.0 - smoothstep(0.0, 0.016, abs(pFender(vec2(qx, zig)))));
    /* 4. задний фонарь — узкая полоса по корме, НА КУЗОВЕ (ниже подоконника):
       в первом варианте он попадал в полосу стекла и читался красной ниткой в окне. */
    float lamp = step(-1.86, qx) * step(qx, -1.06) * (1.0 - smoothstep(0.004, 0.022, abs(zig - 0.905)));
    bodyCol = mix(bodyCol, uDanger * 0.55, lamp * (1.0 - beltZ));
    /* 5. зеркало с ножкой на уровне подоконника */
    float mir = 1.0 - smoothstep(0.0, 0.058, length((vec2(qx, zig) - vec2(0.74, 1.06)) * vec2(1.5, 1.0)));
    bodyCol = mix(bodyCol, uNight * 0.50, mir);
    /* 6. антенна-плавник на крыше */
    float fin = 1.0 - smoothstep(0.0, 0.040, length((vec2(qx, zig) - vec2(-1.42, 1.655)) * vec2(2.4, 1.0)));
    bodyCol = mix(bodyCol, uNight * 0.55, fin);
    }

    col = mix(col, mix(bodyCol, col, 0.35 * (1.0 - fogC)) * (0.55 + 0.45 * fogC), inside);


    /* колёса */
    col = wheel(col, q, CAR_AXLE_F, fogC);
    col = wheel(col, q, CAR_AXLE_R, fogC);

    /* контровой свет по кромке: сверху латунь, снизу медь. Нормаль не считаем —
       4 лишних вызова carSdf стоили бы ~120 операций на пиксель, а свет и так
       поставлен сверху-справа, поэтому хватает маски кромки и высоты. */
    float edge = 1.0 - smoothstep(0.0, 0.016, abs(sd));
    float up = smoothstep(-0.25, 0.30, q.y);
    col += mix(uCopper, uBrass, up) * edge * (0.30 + 0.62 * fogC) * (0.30 + 0.70 * up);

    /* фары и габариты: два мягких ореола, без источника света в кадре */
    /* Фары и габариты: узкие (0,05 L) и внутри габарита. Раньше это были мягкие
       пятна радиусом 0,2 L — они выходили за нос и корму и растягивали видимую
       длину машины на 30 %, из-за чего h/L в замере падал до 0,25. */
    float hl = exp(-length((q - vec2(0.86, -0.03)) * vec2(1.0, 2.8)) * 16.0);
    col += uBrass * 0.50 * hl * inside;
    float tl = exp(-length((q - vec2(-0.88, -0.02)) * vec2(1.0, 3.0)) * 15.0);
    col += uDanger * 0.36 * tl * inside;

    /* отражение в мокром асфальте — самый дорогой кусок B (второй проход carSdf),
       поэтому на low/mid его нет вовсе. */
    if (uQuality > 1.5) {
      float rg = 2.0 * CAR_GROUND - q.y;           /* зеркало относительно линии земли */
      if (rg > CAR_GROUND) {
        vec2 rq = vec2(q.x + (vnoise(vec2(q.y * 3.1, t * 0.7)) - 0.5) * 0.09, rg);
        float rsd = carSdf(rq);
        float fade = exp(-max(CAR_GROUND - q.y, 0.0) * 3.4);
        float rIn = (1.0 - smoothstep(-0.006, 0.012, rsd)) * fade;
        col = mix(col, bodyCol * 0.42, rIn * 0.40);
        col += mix(uCopper, uBrass, 0.5) * (1.0 - smoothstep(0.0, 0.030, abs(rsd))) * rIn * 0.16;
      }
    }
  }

  /* ---------- виньетка, появление, дизеринг ---------- */
  float vig = smoothstep(1.75, 0.30, length(p * vec2(0.60, 0.95)));
  col *= 0.68 + 0.32 * vig;

  col = mix(base, col, uFade);

  /* Дизеринг обязателен: на 8-бит тёмный градиент даёт полосы уже на 300 px.
     Зерно неподвижно в кадре (hash от gl_FragCoord), поэтому не «кипит». */
  col += (hash21(gl_FragCoord.xy) - 0.5) * (1.0 / 255.0);

  gl_FragColor = vec4(col, 1.0);
}`;

