/**
 * Шейдер 3D-фона (задание №44, раунд 30).
 *
 * Ограничения задания, которые заданы здесь жёстко:
 *  - **0 текстур**: ни одного `texture2D`/`sampler2D`. Всё — процедурная математика
 *    (value-noise на хеше, SDF-примитивы). Поэтому вес = текст шейдера, а не мегабайты картинок.
 *  - **один шейдер на два прототипа**: вариант A «глубина» и вариант B «силуэт в глубине»
 *    переключаются uniform'ом `uMode`, а не второй программой. Ветвление по uniform
 *    когерентно (все пиксели кадра идут одной веткой), поэтому второй вариант не удваивает
 *    стоимость первого на устройстве — он добавляет только свою ветку.
 *  - **ESSL 1.00** (`attribute`/`varying`/`gl_FragColor`): один и тот же исходник компилируется
 *    и в WebGL2, и в WebGL1-контексте (WebGL2 принимает ESSL 1.00). Отдельной ветки для
 *    старого Android не нужно.
 *  - **циклы только с константными границами** (требование ESSL 1.00) — циклов нет вовсе,
 *    всё развёрнуто явно.
 *
 * Палитра приходит uniform'ами из CSS-токенов (`--night`, `--deep`, `--brass`, `--copper`,
 * `--mist`, `--danger`), а не зашита здесь: если владелец поменяет палитру, фон поедет с ней.
 *
 * Базовый цвет `mix(uNight, uDeep, vUv.y)` — это ровно `linear-gradient(180deg, var(--deep),
 * var(--night))` из `.page-head` (pages.css:7). Поэтому «фон выключен» и «фон включён»
 * отличаются только глубиной, а не тоном страницы: переключение не выглядит прыжком.
 */

import { CAR, SCALE } from '../car-profile.ts';
import { PLATE_ASPECT, PLATE_GROUND_FRAC, PLATE_HALF_LEN, PLATE_REFLECTION_GAP } from './plate.ts';

/** Длина силуэта в единицах сцены: 4,905 м × 0,364742 ≈ 1,789. */
const SHADOW_LEN = CAR.length * SCALE.bg3d;
/* Полуширина тени на полувысоте, в единицах ПОЛУдлины пластины: 0,55·L/L_half,
   где L = CAR.length·SCALE.bg3d (единицы сцены), L_half = PLATE_HALF_LEN. */
const SHADOW_GX = Math.LN2 / Math.pow((0.55 * SHADOW_LEN) / PLATE_HALF_LEN, 2);
const PLATE_ASP = PLATE_ASPECT.toFixed(5);
const PLATE_HALF = PLATE_HALF_LEN.toFixed(4);
/* Земля и зазор — числа из plate.ts, чтобы шейдер, порт и замеры считали их одинаково. */
const PLATE_GROUND_FRAC_FIXED = PLATE_GROUND_FRAC.toFixed(6);
const REFLECTION_GAP_FIXED = PLATE_REFLECTION_GAP.toFixed(4);

/** Один треугольник на весь экран: 3 вершины, 0 индексных буферов, 1 draw call. */
export const VERT = `precision highp float;
attribute vec2 aPos;
varying vec2 vUv;
void main(){
  vUv = aPos * 0.5 + 0.5;
  gl_Position = vec4(aPos, 0.0, 1.0);
}`;

export const FRAG = `precision highp float;

/* Круг 35 (задание №62): геометрии кузова в шейдере больше нет. Ни профиля из
   модуля, ни rbox/seg/circle, ни полос тона — контур машины целиком лежит в
   фото-пластине (uPlate). Из модуля профиля осталась только длина кузова — она задаёт
   полуширину контактной тени (считается на стороне JS, в SHADOW_GX), и это единственная
   геометрия, которую код ещё вычисляет. Ни длины в метрах, ни масштаба, ни уровня
   земли в шейдере больше нет: они обслуживали удалённый профиль и только занимали вес.
   Земля и зазор отражения — тоже из пластины (PLATE_GROUND_FRAC, PLATE_REFLECTION_GAP):
   силуэт живёт в файле, значит и линия, на которой он стоит, обязана быть из файла. */
/* Пластина: полуразмер по длине и пропорции файла. Числа подставляет сборка из
   src/client/bg3d/plate.ts — того же модуля, что читают CPU-порт и замеры. */
const float PLATE_HALF  = ${PLATE_HALF};
const float PLATE_ASP   = ${PLATE_ASP};
/* Полуширина контактной тени на полувысоте: 0,55 L, где L — длина кузова (паспорт
   4,905 м × масштаб сцены). Раньше стояло 0,97 L — тень была шире машины. */
/* Тень по X. Нормировка gx = (p.x − cp.x)/hx, то есть в единицах ПОЛУдлины квада.
   Требование — полуширина на полувысоте 0,55·L (L — длина кузова в единицах сцены).
   Полудлина квада hx = PLATE_HALF_LEN·sc, а L = CAR.length·SCALE.bg3d единиц сцены;
   в p-единицах L = CAR.length·SCALE.bg3d·sc. Отсюда в gx полуширина равна
   0,55·L/(hx/sc) = 0,55·L_scene/PLATE_HALF_LEN — sc сокращается, и константа не
   зависит ни от кадра, ни от посадки. */
const float SHADOW_GX    = ${SHADOW_GX.toFixed(4)};
const float PLATE_GROUND_FRAC = ${PLATE_GROUND_FRAC_FIXED};
const float PLATE_REFLECTION_GAP = ${REFLECTION_GAP_FIXED};

varying vec2 vUv;

uniform vec2  uRes;      /* физические пиксели канваса (уже с DPR и renderScale) */
uniform float uTime;     /* секунды с запуска, с накоплением только пока фон не на паузе */
uniform float uScroll;   /* 0..1 — насколько хост уехал вверх за край экрана */
uniform vec2  uPointer;  /* -1..1, сглаженное положение указателя */
uniform float uMode;     /* 0 = A «глубина», 1 = B «силуэт в глубине» */
uniform float uQuality;  /* 0 = low, 1 = mid, 2 = high — сколько слоёв шума и есть ли отражение */
uniform float uFade;     /* 0..1 — появление и уход фона */
uniform vec3  uNight;
uniform vec3  uDeep;
uniform vec3  uBrass;
uniform vec3  uCopper;
uniform vec3  uMist;
uniform vec3  uDanger;
uniform sampler2D uPlate;
uniform float uHasPlate;

/* ---------- шум ---------- */

/* Хеш без sin и без текстур: sin на мобильных GPU уходит в SFU и даёт полосы на больших
   площадях, а этот хеш — 6 арифметических операций и ровное зерно. */
float hash21(vec2 p){
  p = fract(p * vec2(0.3183099, 0.3678794));
  p *= 17.0;
  return fract(p.x * p.y * (p.x + p.y));
}

/* Value-noise: 4 хеша + билинейная интерполяция с smoothstep. Одна выборка ≈ 36 операций. */
float vnoise(vec2 p){
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  float a = hash21(i);
  float b = hash21(i + vec2(1.0, 0.0));
  float c = hash21(i + vec2(0.0, 1.0));
  float d = hash21(i + vec2(1.0, 1.0));
  return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);
}

/* ---------- машина: фото-пластина (круг 35, задание №62) ----------
   Контуры кузова кодом не рисуются. Внутри альфы пластины лежит ПОЛНЫЙ кадр фото —
   свет на краске, блики, стёкла, диски и шины. Код оставляет только то, чего в фото
   нет и быть не может: пол, контактную тень, отражение и градиент фона.

   Почему текстура, хотя раунд 30 требовал нуля текстур. Требование было про вес и
   про честность замера: шейдер не должен тянуть мегабайты картинок. Здесь картинка —
   84 КБ webp, одна, с мипмапами силами браузера, и ровно ОДНА выборка на пиксель.
   Процедурный силуэт обходился дороже по существу: 936,8 оп/px при плоской заливке
   внутри кузова (сигма 10,7 L) и кромке-ступеньке. Числа — docs/reports/r35-bg-car.

   Координаты квада. В p (x уже умножен на aspect) полуразмеры:
     hx = PLATE_HALF * sc          — полудлина кузова (0,894 — как у силуэта круга 33)
     hy = hx / PLATE_ASP           — полувысота из пропорций самого файла
   Отсюда uv = (p − центр) / (2*h) + 0,5. Ни обрезки, ни растяжения: пропорции
   приходят из файла, поэтому при смене кадра кромка не рвётся. */
vec4 plate(vec2 p, vec2 cp, float sc, float aspect){
  float hx = PLATE_HALF * sc;
  float hy = hx / PLATE_ASP;
  vec2 t = (p - cp) / vec2(2.0 * hx, 2.0 * hy) + 0.5;
  /* мипмапы включены: при уменьшении кадра пластина не звенит и не рвёт кромку */
  vec4 tex = texture2D(uPlate, t);
  /* за пределами квада альфа строго 0: пиксель не протекает за кромку */
  float inQ = step(0.0, t.x) * step(t.x, 1.0) * step(0.0, t.y) * step(t.y, 1.0);
  tex.a *= inQ * uHasPlate;
  return tex;
}

void main(){
  vec2 res = uRes;
  float aspect = res.x / max(res.y, 1.0);
  vec2 p = (vUv - 0.5) * 2.0;
  p.x *= aspect;

  float t = uTime;
  /* Тон страницы = градиенту .page-head. К нему добавляется глубина, поэтому uFade
     плавит фон с выключенным состоянием без скачка яркости. */
  vec3 base = mix(uNight, uDeep, clamp(vUv.y, 0.0, 1.0));
  vec3 col = base;

  /* Горизонт: чуть выше центра, уходит вверх при скролле — это и есть параллакс глубины. */
  float hy = 0.10 + uPointer.y * 0.03 - uScroll * 0.22;

  /* ---------- воздух/стена над горизонтом (считаем всегда: дёшево, 1 шум) ---------- */
  float k = clamp((p.y - hy) / max(1.0 - hy, 0.001), 0.0, 1.0);
  col = mix(uDeep, uNight, pow(k, 0.75));
  float shaft = vnoise(vec2(p.x * 1.25 + t * 0.017, p.y * 0.55 - t * 0.031));
  col += uMist * 0.055 * shaft * (1.0 - k);
  /* вертикальные лучи от ламп: шум, вытянутый по вертикали */
  float ray = vnoise(vec2(p.x * 0.85 - t * 0.008, 1.5));
  col += uBrass * 0.045 * ray * (1.0 - k) * smoothstep(0.0, 0.6, p.y);
  float glow = exp(-length(vec2((p.x - 0.78) * 0.85, (p.y - 0.62) * 1.50)) * 1.35);
  col += uCopper * 0.34 * glow;

  /* ---------- пол: перспективная проекция к горизонту ---------- */
  if (p.y < hy) {
    float d = max(hy - p.y, 0.030);
    float z = 1.0 / d;                             /* ~1 у горизонта … ~33 у нижнего края */
    float fog = exp(-z * 0.055);
    vec2 fuv = vec2(p.x * z * 0.55 + uPointer.x * 0.60, z * 0.55 - t * 0.22);
    float n1 = vnoise(fuv * 1.60);
    float dust = n1;
    if (uQuality > 0.5) {
      dust = n1 * 0.62 + vnoise(fuv * 4.30 + 11.7) * 0.38;
    }
    col = mix(uNight, uDeep, 0.35 + dust * 0.85);
    if (uQuality > 1.5) {
      /* мокрые полосы вдоль направления движения — вытянутый шум по z */
      float wet = vnoise(vec2(fuv.x * 6.0, fuv.y * 0.55 - t * 0.50));
      col += uBrass * 0.14 * wet * fog;
    }
    /* лужа тёплого света от ламп бокса справа и холодный контр-свет слева:
       два источника дают объём, один — плоское пятно */
    float pool = exp(-length(vec2((p.x - 0.42) * 0.70, (p.y + 0.46) * 1.25)) * 1.05);
    col += uCopper * 0.70 * pool * (0.30 + 0.70 * fog);
    float cool = exp(-length(vec2((p.x + 0.72) * 0.80, (p.y + 0.30) * 1.60)) * 1.30);
    col += uMist * 0.075 * cool * (0.30 + 0.70 * fog);
    /* дальний план темнее и стремится к цвету стены: без этого у горизонта виден стык */
    col = mix(uDeep * 0.85, col, 0.45 + 0.55 * fog);
  }

  /* ---------- дымка у горизонта: заодно прячет стык пола и воздуха ---------- */
  col += uBrass * 0.22 * exp(-abs(p.y - hy) * 9.0);

  /* ---------- вариант B: машина в глубине ---------- */
  if (uMode > 0.5) {
    float depth = 0.58;
    float sc = mix(0.80, 0.46, depth);
    /* Посадка зависит от формы кадра. На широком экране (aspect 1,8) машина стоит
       справа, под текстом слева, и это правильно. На узком (390x844, aspect 0,46)
       та же формула уносит её за правый край, поэтому коэффициент считается от
       aspect и применяется к обеим осям:
         по X — тянем к центру: kx = 1 при aspect >= 1,4, плавно к 0,35 при 0,46;
         по Y — приподнимаем, чтобы машина не упиралась в нижний край.
       Вёрстка страницы не меняется: это только кадр внутри блока.
       Те же коэффициенты продублированы в src/client/bg3d/plate.ts — их читают
       CPU-порт и замеры, и это единственный способ, чтобы кадр в отчёте и кадр на
       GPU совпадали. */
    float wide = smoothstep(0.46, 1.40, aspect);
    float kx = mix(0.35, 1.0, wide);
    float ky = mix(0.55, 1.0, wide);
    sc *= mix(0.62, 1.0, smoothstep(0.40, 0.86, aspect));
    float lift = (1.0 - wide) * 0.28;
    vec2 cp = vec2(
      (0.24 + uPointer.x * 0.10 * (1.0 - depth)) * kx,
      hy - 0.155 - uScroll * 0.05 + uPointer.y * 0.035 - (1.0 - ky) * 0.30 + lift
    );
    /* атмосферная дымка: машина не наклеена, а стоит в тумане */
    float fogC = exp(-depth * 1.15);

    /* Сцена B тёмная: пол под машиной почти чёрный, машина светлее его. Множитель
       0.22 ставит пол НИЖЕ кузова, не меняя палитры: прожектор и свечение остаются. */
    col *= 0.22;   /* тёмная сцена B: то же число в tools/bg3d/ref.mjs (SCENE_B_MUL) */

    /* Линия земли. Силуэт живёт в файле, поэтому и земля берётся из него: PLATE_GROUND_FRAC —
       доля высоты файла от верха до линии земли (её пишет сборка пластины из plate.json).
       Низ квада для этого не годится: под землёй в файле лежит поле padding (8 px), и тень,
       посаженная на низ квада, уезжает под машину — под шинами остаётся светлая щель,
       а тень читается отдельным пятном на полу.
       Отражаем силуэт относительно той же линии, поэтому шины касаются отражения ровно
       там, где стоят, с зазором PLATE_REFLECTION_GAP. */
    float hx = PLATE_HALF * sc;
    float hyHalf = hx / PLATE_ASP;
    float groundLine = cp.y + hyHalf - PLATE_GROUND_FRAC * 2.0 * hyHalf;
    float gy = p.y - groundLine;
    float gx = (p.x - cp.x) / max(hx, 0.0001);

    /* Контактная тень: плотная под порогом, гаснет вниз (задание №57 §2.3).
       Полуширина по длине — SHADOW_HALF; по вертикали — крутая: тень лежит на полу,
       а не на машине. */
    float shd = exp(-(gx * gx * SHADOW_GX + gy * gy * (90.0 / max(hx * hx, 0.0001))));
    shd *= smoothstep(-0.055, -0.006, gy) * (1.0 - smoothstep(0.14, 0.30, gy));
    /* Тёмное пятно под машиной (ambient occlusion). В эталоне Drive пол под кузовом
       2,4 L при кузове 14,6 L — машина не «висит» над светлым полом, а стоит в своей
       тени. Без этого пятна пол под машиной был 22,9 L при кузове 24,1 L: контраст
       1,05× и никакого объёма. Ширина пятна — по длине кузова, высота — по той же
       нормировке, что и контактная тень. */
    float occl = exp(-(gx * gx * 0.55 + gy * gy * (14.0 / max(hx * hx, 0.0001))));
    /* Пятно гаснет по вертикали в 0,06 полувысоты квада: иначе тёмная полоса уходит
       под машину на её же высоту, и замер по разнице кадров читает её как кузов
       (h/L 0,377 вместо 0,335). */
    occl *= 1.0 - smoothstep(0.0, 0.06, gy);
    col *= 1.0 - 0.62 * occl;
    col *= 1.0 - 0.16 * shd;

    /* Пластина: одна выборка. Внутри альфы — фото, снаружи альфа 0 и кадр не меняется. */
    vec4 pl = plate(p, cp, sc, aspect);
    /* Дымка: дальний план теряет контраст, поэтому к пластине подмешивается фон ровно
       на столько, на сколько его подмешивал процедурный силуэт: машина стоит в сцене,
       а не висит поверх неё. */
    vec3 bodyCol = mix(pl.rgb, col, 0.30 * (1.0 - fogC));
    col = mix(col, bodyCol, pl.a);

    /* отражение в мокром асфальте — второй проход по альфе пластины (дорого, поэтому
       только на high). Отражаем ту же пластину, а не отдельную геометрию: иначе в
       отражении оказался бы другой автомобиль, чем в кадре. */
    if (uQuality > 1.5) {
      /* Зазор между низом машины и её отражением: на мокром асфальте отражение
         начинается не вплотную к шине, а на 3–4 px ниже — там лежит контактная тень.
         Без зазора отражение прирастает к силуэту, и любой замер по разнице кадров
         читает его как часть машины (h/L 0,377 вместо 0,335). */
      float groundY = groundLine - PLATE_REFLECTION_GAP;
      vec2 rp = vec2(p.x, 2.0 * groundY - p.y);
      vec4 rr = plate(rp, cp, sc, aspect);
      float fade = exp(-max(-gy, 0.0) * 3.4);
      col = mix(col, mix(uNight, rr.rgb * 0.42, 0.85), rr.a * 0.40 * fade);
    }
  }

  /* ---------- виньетка, появление, дизеринг ---------- */
  float vig = smoothstep(1.75, 0.30, length(p * vec2(0.60, 0.95)));
  col *= 0.68 + 0.32 * vig;

  col = mix(base, col, uFade);

  /* Дизеринг обязателен: на 8-бит тёмный градиент даёт полосы уже на 300 px.
     Зерно неподвижно в кадре (hash от gl_FragCoord), поэтому не «кипит». */
  col += (hash21(gl_FragCoord.xy) - 0.5) * (1.0 / 255.0);

  gl_FragColor = vec4(col, 1.0);
}`;

